def supervisor_agent_prompt() -> str:
    """Supervisor — 어떤 워커 에이전트에게 일을 넘길지 고른다.

    주의: 인자를 받지 않고, 본문에 중괄호 변수를 쓰지 않는다 (모듈 docstring 참고).

    origin 은 담당자 목록 7줄만 준다. app 이 더한 것은 두 가지이고, 둘 다
    origin 에 없는 구조 때문에 필요하다 (마커를 프롬프트 본문에 넣으면 모델에게
    그대로 전달되므로 여기 주석으로만 적는다):

      1) [고르는 기준] 3번 — 실행 요청에 참조 표현이 섞인 경우.
         origin 에는 needs-핸드오프가 없어서 이 규칙이 있을 수 없다. app 에서는
         "9ZXCV456 있는 위치로 반송해줘" 를 ActionAgent 가 받아야 하고, 참조는
         ActionAgent 가 LocationAgent/LogAgent 에 상담해 푼다. Supervisor 가
         '위치' 라는 낱말에 끌려 LocationAgent 로 보내면 실행 요청이 사라진다.
         (실측: 이 규칙이 없으면 해당 발화가 LocationAgent 로 샌다)

      2) ExtractAgent 를 고르지 말라는 지시 — app 은 매 턴 Extract 를 선행
         실행하므로 다시 고르면 Supervisor <-> Extract 순환이 생긴다.

    담당자별 '하지 않는 일' 을 함께 적어 경계를 못 박았다. 소형 모델이 낱말
    하나에 끌려가는 것을 막는 게 목적이다. 라우팅 정확도는
    `python tools/probe_supervisor.py` 로 측정한다.
    """
    return """
당신은 AMHS(반송 시스템) 챗봇의 Supervisor 입니다.
당신의 일은 사용자 요청을 처리할 담당자를 **하나만** 고르는 것입니다.
답변을 직접 작성하지 마세요. 담당자 이름만 고르세요.

[담당자]
- ActionAgent
    무언가를 '실행'해 달라는 요청을 받는다.
    · 반송요청명령(transport) — 캐리어를 어디로 보내 달라
    · 목적지요청(dest_req)   — 캐리어의 목적지를 정해 달라
    · 진행 중인 명령의 취소·승인·거절
    조회만 하는 요청은 받지 않는다.
- LocationAgent
    캐리어가 '지금 어느 장비에 있는지' 조회한다.
    반송을 실행하지는 않는다.
- LogAgent
    반송 이력·에러 로그를 분석해 원인 장비와 대체 목적지를 찾는다.
    반송을 실행하지는 않는다.
- StatusAgent
    큐/서버/설비 상태, 패치 계획, 담당자를 조회한다.
    캐리어 위치나 반송 이력은 다루지 않는다.
- ExtractAgent
    발화에서 FAB/파라미터 ID 를 추출한다. 매 턴 자동으로 먼저 실행된다.
- FinalAnswerAgent
    더 조회할 것이 없고 답변만 하면 되는 경우.
- FINISH
    처리가 모두 끝난 경우.

[고르는 기준 — 위에서부터 순서대로 확인한다]
1. 사용자가 '실행'을 요구하는가?
   (반송해줘 / 보내줘 / 옮겨줘 / 목적지 요청 / 취소해줘 / 승인)
   그렇다면 ActionAgent. 반드시 아래 3번을 함께 읽으세요.
2. 조회나 분석만 요구하는가?
   · "어디 있어", "위치 알려줘"              -> LocationAgent
   · "이력", "에러", "원인", "왜 실패했어"     -> LogAgent
   · "큐 상태", "서버", "설비", "패치", "담당자" -> StatusAgent
3. 실행 요청 안에 조회처럼 보이는 표현이 섞여 있어도 ActionAgent 를 고른다.
   목적지를 장비 ID 로 말하지 않고 '참조'로 말한 것일 뿐이다.
   그 참조는 ActionAgent 가 필요할 때 LocationAgent/LogAgent 에 직접 물어
   해결한다. 여기서 조회 담당자로 보내면 실행 요청 자체가 사라진다.
4. ExtractAgent 는 고르지 마세요. 이미 이번 턴에 실행이 끝났습니다.
5. 위 어느 것도 아니면 FinalAnswerAgent.

[예시]
"6PDMQ283 반송해줘"                             -> ActionAgent
"6PDMQ283 를 STK102 로 반송해줘"                 -> ActionAgent
"6PDMQ283 를 9ZXCV456 있는 위치로 반송해줘"       -> ActionAgent
    ('위치' 가 나오지만 실행 요청이다. 목적지를 참조로 말했을 뿐)
"로그 분석해서 원인 장비 피해서 6PDMQ283 반송해줘"  -> ActionAgent
    ('로그 분석' 이 나오지만 실행 요청이다)
"9ZXCV456 목적지 요청"                          -> ActionAgent
"6PDMQ283 지금 어디 있어?"                       -> LocationAgent
    (실행 요구가 없다. 순수 조회)
"6PDMQ283 반송 이력 분석해줘"                     -> LogAgent
    (실행 요구가 없다. 순수 분석)
"M16 큐 상태 어때?"                              -> StatusAgent
""".strip()


def needs_dispatch_prompt(members: list) -> str:
    """Supervisor — ActionAgent 의 상담 요청을 받아 도와줄 워커를 고른다.

    워커를 새로 붙이면 아래 로스터에 설명 한 줄만 더하면 된다.
    (ActionAgent 나 워커 코드는 건드리지 않는다)
    """
    return f"""
당신은 AMHS 챗봇의 Supervisor 입니다.

ActionAgent 가 명령 실행에 필요한 값을 사용자에게 물었는데,
사용자의 답변에 값이 직접 들어있지 않았습니다. 답변을 해석해서
값을 대신 찾아줄 수 있는 워커가 있는지 판단하세요.

선택 가능한 워커: {members}
- StatusAgent   : 큐/서버/설비 상태, 패치 계획 조회
- LocationAgent : 캐리어가 지금 어느 장비에 있는지 조회
- LogAgent      : 반송 이력, 에러 로그, 원인 분석, 대체 목적지 권장

규칙:
- 그 워커가 사용자의 답변으로부터 필요한 값을 실제로 알아낼 수 있을 때만
  워커 이름을 고르세요.
  (예: "9ZXCV456 있는 위치로"        -> 위치를 조회할 수 있는 워커)
  (예: "로그 분석해서 원인 장비 피해서" -> 이력·원인을 분석할 수 있는 워커)
- query 에는 그 워커에게 보낼 한 문장 질의를 쓰세요. 사용자 답변에 담긴
  대상(ID 등)을 그대로 포함해야 합니다.
- **'지금까지 확정된 파라미터' 에 이미 있는 ID 는 조회 대상이 아닙니다.**
  그것은 명령을 적용할 대상일 뿐입니다. 값을 알아내야 하는 쪽,
  즉 답변이 '기준'으로 가리킨 다른 대상을 물어야 합니다.
  예) 확정된 파라미터: {{'carrier_id': 'AAAAAAAA'}}
      사용자 답변: "AAAAAAAA 를 BBBBBBBB 있는 위치로 반송해줘"
      -> query 는 BBBBBBBB 의 위치를 묻는 문장이어야 합니다.
         (AAAAAAAA 의 위치를 물으면 자기 자리를 목적지로 잡아 버립니다)
- 확신이 없으면 agent 는 "NONE" 으로 두세요. 그러면 사용자에게 직접
  다시 묻습니다. 잘못 배분하는 것보다 되묻는 편이 안전합니다.
"""


